import { describe, expect, it } from 'vitest';

import { renderConversionSql } from '../../scripts/convert-split-to-dlc.mjs';

/**
 * The one-off that turns an imported `"53 + 6"` year split into a DLC row
 * (`scripts/convert-split-to-dlc.mjs`) is a pure SQL emitter — no database,
 * no network — so what it decides is testable here. The SQL is applied by
 * hand (psql locally, the Supabase MCP in production).
 */
const ENTRIES = [
  { title: 'Clair Obscur: Expedition 33', year: 2026 },
  { title: 'Lies of P', year: 2025 },
  { title: 'Hollow Knight', year: 2025 },
] as const;

describe('renderConversionSql', () => {
  const sql = renderConversionSql(ENTRIES);

  it('wraps everything in one transaction with a header comment', () => {
    expect(sql.startsWith('-- Generated by scripts/convert-split-to-dlc.mjs')).toBe(true);
    expect(sql).toContain('\nBEGIN;\n');
    expect(sql.trimEnd().endsWith('COMMIT;')).toBe(true);
  });

  it('emits one block per entry, keyed by title and the year being moved', () => {
    expect(sql.match(/insert into game_dlc/gi)).toHaveLength(3);
    expect(sql).toContain("g.title = 'Clair Obscur: Expedition 33' and py.year = 2026");
    expect(sql).toContain("g.title = 'Lies of P' and py.year = 2025");
    expect(sql).toContain("g.title = 'Hollow Knight' and py.year = 2025");
  });

  it('names the new row DLC, lowers the base hours by the moved tenths, and deletes the split', () => {
    expect(sql).toContain("'DLC'");
    expect(sql).toMatch(/set hours_tenths = hours_tenths - \(/i);
    expect(sql).toMatch(/updated_at = now\(\)/i);
    expect(sql).toMatch(/delete from game_play_years where game_id/i);
  });

  it('escapes a quote in a title', () => {
    const one = renderConversionSql([{ title: "Marvel's Spider-Man", year: 2025 }]);
    expect(one).toContain("g.title = 'Marvel''s Spider-Man'");
  });

  it('refuses an empty list rather than emitting an empty transaction', () => {
    expect(() => renderConversionSql([])).toThrow(/nothing to convert/i);
  });
});
