/**
 * Turns an imported "base + DLC" year split into a real DLC row.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY. The sheet wrote `"53 + 6"` to mean "53 hours on the base game, 6 more
 * on the DLC the next year". `seed-play-year-splits.mjs` faithfully turned
 * that into a `game_play_years` split — the only model there was at the time.
 * Now DLC is a row of its own (`game_dlc`, additive — see
 * `src/server/games/dlc.ts`), the owner has said which splits were DLC, and
 * this emits the SQL that moves each one across. Per game:
 *
 *   1. insert one `game_dlc` row named `DLC` — a PLACEHOLDER the owner renames
 *      in the panel, where they also fill trophies and price — with the moved
 *      year and the moved hours;
 *   2. lower `games.hours_tenths` by the moved tenths (the total is now the
 *      base game alone; the DLC adds back on top at read time);
 *   3. delete the game's `game_play_years` rows — the one row left would only
 *      restate `first_played_year`, which attribution falls back to anyway.
 *
 * PURE. No database, no network, no environment variables — the same contract
 * as `diff-game-log.mjs`. Title-keyed data is a one-off, never a migration
 * (`docs/GAMES.md`): ids differ between the local database and production,
 * so the SQL joins on `title` and is applied by hand — `psql` locally, the
 * Supabase MCP in production. Each block is a no-op when the title or the
 * year is not found, so re-running it cannot double-move anything: the
 * second run finds no split row to move.
 *
 *   node scripts/convert-split-to-dlc.mjs <map.json> --out <file.sql>
 *
 * `map.json` is `[{ "title": "<exact games.title>", "year": <year moved> }]`.
 * ─────────────────────────────────────────────────────────────────────────────
 */

import fs from 'node:fs';
import process from 'node:process';
import { pathToFileURL } from 'node:url';

import { sqlLiteral } from './diff-game-log.mjs';

/**
 * @param {ReadonlyArray<{ readonly title: string; readonly year: number }>} entries
 * @returns {string}
 */
export function renderConversionSql(entries) {
  if (entries.length === 0) throw new Error('Nothing to convert: the map is empty.');

  const blocks = entries.map(({ title, year }) => {
    if (!Number.isInteger(year)) throw new Error(`Year for "${title}" is not an integer: ${year}`);
    const t = sqlLiteral(title);
    return [
      `-- ${title}: the ${year} split becomes a DLC row.`,
      'with moved as (',
      '  select g.id as game_id, g.owner_id, py.year, py.hours_tenths',
      '  from games g',
      '  join game_play_years py on py.game_id = g.id',
      `  where g.title = ${t} and py.year = ${year}`,
      ')',
      'insert into game_dlc (owner_id, game_id, name, year, hours_tenths)',
      `select owner_id, game_id, 'DLC', year, hours_tenths from moved;`,
      '',
      'with moved as (',
      '  select g.id as game_id, py.hours_tenths',
      '  from games g',
      '  join game_play_years py on py.game_id = g.id',
      `  where g.title = ${t} and py.year = ${year}`,
      ')',
      'update games',
      'set hours_tenths = hours_tenths - (select hours_tenths from moved), updated_at = now()',
      'where id = (select game_id from moved);',
      '',
      'delete from game_play_years where game_id in (',
      `  select id from games where title = ${t}`,
      ');',
      '',
    ].join('\n');
  });

  return [
    `-- Generated by scripts/convert-split-to-dlc.mjs on ${new Date().toISOString().slice(0, 10)}.`,
    '-- Each block: insert the DLC row, lower the base hours, drop the now-redundant split.',
    '-- Applied by hand; see the script header. Safe to re-run: a moved split is gone.',
    'BEGIN;',
    '',
    ...blocks,
    'COMMIT;',
    '',
  ].join('\n');
}

function main() {
  const [mapPath, ...rest] = process.argv.slice(2);
  const outIndex = rest.indexOf('--out');
  const outPath = outIndex >= 0 ? rest[outIndex + 1] : undefined;
  if (mapPath === undefined || outPath === undefined) {
    console.error('Usage: node scripts/convert-split-to-dlc.mjs <map.json> --out <file.sql>');
    process.exit(2);
  }
  const entries = JSON.parse(fs.readFileSync(mapPath, 'utf8'));
  fs.writeFileSync(outPath, renderConversionSql(entries));
  console.log(`Wrote ${outPath}: ${entries.length} conversion block(s).`);
}

const isDirectRun =
  process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isDirectRun) main();
