#!/usr/bin/env node
/**
 * One-off correction of `games.platform` for the 160 games already imported
 * by scripts/import-game-log.mjs.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * WHY THIS EXISTS
 *
 * import-game-log.mjs derives platform from SECTION POSITION in the sheet
 * (see `guessPlatform` there), because the CSV export has no Platform column
 * at all. That guess turned out to be wrong: the owner's real signal was the
 * spreadsheet row's CELL BACKGROUND COLOUR (the sheet's own legend:
 * A4C2F4->ps5, C9DAF8->ps4, EAD1DC->psp, B6D7A8->steam/pc), which the CSV
 * export destroys completely — colour never survives a CSV round-trip. The
 * owner recovered the real title->platform mapping from the sheet's `.xlsx`
 * export, outside this script, and this script applies that confirmed
 * mapping to the rows already sitting in the database. In particular, every
 * modern PlayStation title had been imported as `ps5` with no ps4/ps5 split
 * at all — the recovered map is what corrects that.
 *
 * Run manually, once, against the already-imported library. Not wired into
 * any product flow, not a feature — same shape as import-game-log.mjs. Safe
 * to re-run: a row whose platform already matches the map is reported as
 * "already correct" and left untouched, never re-written.
 *
 * Usage:
 *   node scripts/fix-game-platforms.mjs <path-to-platform-map.json> <owner-email>
 *
 * The map JSON is `{ "Title": "ps5" | "ps4" | "psp" | "steam", ... }`,
 * generated by hand from the owner's `.xlsx` export. It is the owner's real
 * game library and lives OUTSIDE this repo — it is never committed here, the
 * same rule CLAUDE.md holds Finance to for real financial data.
 *
 * WHY PLAIN ESM AND NOT TYPESCRIPT
 *
 * Same reasoning as scripts/import-game-log.mjs: this only needs to read a
 * JSON file and run a few updates, so it needs nothing but `postgres`,
 * already a production dependency.
 * ─────────────────────────────────────────────────────────────────────────────
 */

import { readFile } from 'node:fs/promises';
import process from 'node:process';
import { pathToFileURL } from 'node:url';
import postgres from 'postgres';

// Same set import-game-log.mjs and src/server/db/seed-guard.ts use for the
// identical local-only guard. Duplicated rather than imported: every script
// in this directory is deliberately self-contained (import-game-log.mjs
// makes the same call for the same reason), so a one-off tool doesn't end up
// coupled to a sibling one-off tool that may outlive it or vice versa.
const LOCAL_HOSTNAMES = new Set(['localhost', '127.0.0.1', '::1', '[::1]']);

const VALID_PLATFORMS = new Set(['ps5', 'ps4', 'psp', 'steam', 'pc', 'other']);

/**
 * Collapses whitespace runs and trims the ends. The recovered map carries a
 * handful of titles with stray trailing spaces (an artefact of the `.xlsx`
 * recovery, e.g. `"Bloody Roar 2     "`) that the database's own copy of the
 * same title does not — comparing the two without this would under-match
 * real, correct pairs for a reason that has nothing to do with the games
 * being different.
 *
 * Deliberately case-SENSITIVE: `games`' own uniqueness is case-insensitive
 * per platform (`lower(title)`), so the one duplicate title the original CSV
 * import silently dropped (two rows differing only by case survived export
 * as two map entries, but only one could ever become a database row) must
 * surface here as a genuine non-match, not be quietly folded back together.
 * That is the ONE map entry this script's caller should expect to report as
 * "no matching row" — see the header comment on `matchRow` below.
 */
export function normalizeTitle(title) {
  return title.trim().replace(/\s+/g, ' ');
}

/**
 * Strips a single trailing parenthetical remark, e.g. `"Grand Theft Auto:
 * Vice City (itch)" -> "Grand Theft Auto: Vice City"`. Used ONLY as a
 * fallback when an exact title match fails — never as the primary
 * comparison — because it is a lossy transform that could in principle merge
 * two distinct titles. It is scoped as narrowly as the merchant-name rules
 * in src/server/finance/: strip at most one trailing `(...)`, never touch
 * anything else about the string.
 */
export function stripTrailingParenthetical(title) {
  return title.replace(/\s*\([^)]*\)\s*$/, '').trim();
}

/**
 * Resolves each map entry to the `games` row it describes.
 *
 * Two passes, in order:
 *   1. Exact match on whitespace-normalized title.
 *   2. Fallback: whitespace-normalized title with a trailing parenthetical
 *      stripped from the DATABASE side, matched ONLY when exactly one row
 *      resolves that way (an ambiguous strip is treated as no match at all,
 *      never guessed at) — this is what recovers "Grand Theft Auto: Vice
 *      City" against the database's "Grand Theft Auto: Vice City (itch)"
 *      row, a real store-suffix difference confirmed against the owner's
 *      actual library, not a hypothetical one this function invents a rule
 *      for in the abstract.
 *
 * `rows` must already be scoped to one owner — this function does no
 * ownership filtering of its own.
 */
export function matchRow(rows, rawTitle) {
  const normalized = normalizeTitle(rawTitle);

  const exact = rows.find((row) => normalizeTitle(row.title) === normalized);
  if (exact) return exact;

  const strippedCandidates = rows.filter((row) => {
    const stripped = normalizeTitle(stripTrailingParenthetical(row.title));
    return stripped !== normalizeTitle(row.title) && stripped === normalized;
  });
  return strippedCandidates.length === 1 ? strippedCandidates[0] : null;
}

/**
 * Whether a Postgres connection string points at a local database. Same
 * logic as import-game-log.mjs's `isLocalDatabaseUrl` — see that file's own
 * doc comment for why `[::1]` needs to be in the allowlist as a literal
 * bracketed string, and why unparsable input fails closed.
 */
export function isLocalDatabaseUrl(url) {
  try {
    return LOCAL_HOSTNAMES.has(new URL(url).hostname);
  } catch {
    return false;
  }
}

async function main() {
  const [, , mapPath, ownerEmail] = process.argv;

  if (!mapPath || !ownerEmail) {
    console.error('Usage: node scripts/fix-game-platforms.mjs <path-to-platform-map.json> <owner-email>');
    process.exit(1);
  }

  const databaseUrl = process.env.DATABASE_URL;
  if (!databaseUrl) {
    console.error('DATABASE_URL is not set');
    process.exit(1);
  }

  if (!isLocalDatabaseUrl(databaseUrl)) {
    console.error(
      'Refusing to run against a non-local database. Correct platform data locally, then migrate deliberately.',
    );
    process.exit(1);
  }

  const email = ownerEmail.trim().toLowerCase();
  const sql = postgres(databaseUrl, { max: 1 });

  try {
    const [owner] = await sql`select id from "user" where email = ${email} limit 1`;
    if (!owner) {
      console.error(`No user row for ${email}. Provision the owner first.`);
      process.exitCode = 1;
      return;
    }

    const raw = await readFile(mapPath, 'utf8');
    /** @type {Record<string, string>} */
    const map = JSON.parse(raw);

    const rows = await sql`select id, title, platform from games where owner_id = ${owner.id}`;

    let changed = 0;
    let alreadyCorrect = 0;
    let notFound = 0;

    for (const [rawTitle, platform] of Object.entries(map)) {
      if (!VALID_PLATFORMS.has(platform)) {
        console.error(`Skipping "${rawTitle}": map value "${platform}" is not a recognised platform.`);
        continue;
      }

      const row = matchRow(rows, rawTitle);
      if (!row) {
        notFound += 1;
        console.log(`No matching row for "${rawTitle}".`);
        continue;
      }

      if (row.platform === platform) {
        alreadyCorrect += 1;
        continue;
      }

      await sql`update games set platform = ${platform}, updated_at = now() where id = ${row.id}`;
      changed += 1;
    }

    console.log(
      `Changed ${changed} row(s), ${alreadyCorrect} already correct, ${notFound} map entr${notFound === 1 ? 'y' : 'ies'} with no matching row.`,
    );
  } catch (error) {
    // Log the message only. An update error can echo field values back, and
    // this table — like finance — holds the owner's personal data.
    console.error('Platform correction failed:', error instanceof Error ? error.message : 'unknown error');
    process.exitCode = 1;
  } finally {
    await sql.end();
  }
}

const isDirectRun = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isDirectRun) {
  await main();
}
